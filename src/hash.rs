/// 标准 SHA-256。
pub fn sha256(data: &[u8]) -> [u8; 32] {
    let mut h: [u32; 8] = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
    let mut m = data.to_vec();
    let bits = (data.len() as u64) * 8;
    m.push(0x80);
    while m.len() % 64 != 56 {
        m.push(0);
    }
    m.extend_from_slice(&bits.to_be_bytes());
    for c in m.chunks(64) {
        let mut w = [0u32; 64];
        for i in 0..16 {
            w[i] = u32::from_be_bytes([c[4 * i], c[4 * i + 1], c[4 * i + 2], c[4 * i + 3]]);
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
        }
        let (mut a, mut b, mut cc, mut d, mut e, mut f, mut g, mut hh) = (h[0], h[1], h[2], h[3], h[4], h[5], h[6], h[7]);
        for i in 0..64 {
            let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
            let ch = (e & f) ^ (!e & g);
            let t1 = hh.wrapping_add(s1).wrapping_add(ch).wrapping_add(K[i]).wrapping_add(w[i]);
            let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
            let maj = (a & b) ^ (a & cc) ^ (b & cc);
            let t2 = s0.wrapping_add(maj);
            hh = g; g = f; f = e; e = d.wrapping_add(t1); d = cc; cc = b; b = a; a = t1.wrapping_add(t2);
        }
        for (x, v) in h.iter_mut().zip([a, b, cc, d, e, f, g, hh]) {
            *x = x.wrapping_add(v);
        }
    }
    let mut out = [0u8; 32];
    for i in 0..8 {
        out[4 * i..4 * i + 4].copy_from_slice(&h[i].to_be_bytes());
    }
    out
}

/// sha256(sha256(d))，比特币风格的区块/交易 ID。
pub fn sha256d(d: &[u8]) -> [u8; 32] {
    sha256(&sha256(d))
}

/// 160 位地址摘要：sha256(d)[0..20]（为省行数用截断而非 RIPEMD160）。
pub fn h160(d: &[u8]) -> [u8; 20] {
    let s = sha256(d);
    let mut o = [0u8; 20];
    o.copy_from_slice(&s[..20]);
    o
}

/// Merkle 根：叶子为已有 txid；奇数复制末尾；空集合返回全 0。
pub fn merkle(hs: &[[u8; 32]]) -> [u8; 32] {
    if hs.is_empty() {
        return [0; 32];
    }
    let mut v = hs.to_vec();
    while v.len() > 1 {
        if v.len() % 2 == 1 {
            v.push(*v.last().unwrap());
        }
        v = v.chunks(2).map(|c| {
            let mut b = c[0].to_vec();
            b.extend_from_slice(&c[1]);
            sha256d(&b)
        }).collect();
    }
    v[0]
}
